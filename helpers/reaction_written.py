"""
The written cells: one object, thirteen cats, thirteen different afternoons.

This is the only content. Every line was written for *that* object shown to
*that* class, and nothing here is assembled from parts or filled in by a
template. There used to be a generator standing in for the objects nobody had
reached; it produced things like "has met an accordion before" and it is gone.
An object that is not in this file simply does nothing when it is shown.

**The object joins the fight.** It is thrown in, rolled in, loosed, opened
ringside or landed in the middle of it. It is not held up for the cat to look
at: it is a thing now present in the arena that the cat has to deal with, use,
or be beaten by.

**What the cat does with it is the joke.** A clever cat turns it into an
advantage, a strong cat picks it up and throws it, a stupid cat gets tangled in
it, and a charming cat gets somebody else to hold it. The same octopus is a
weapon, a hiding place, a knot, and a co-operative assistant depending on who is
standing next to it.

**Bigger objects can favour the strong.** A plane in the ring is not automatically
a disaster; a Chonk picks it up by the tail and throws it, and that is the
correct outcome. Do not assume every object is a hazard.

**Swings are real.** Two or three points, across more than one attribute, when
the story earns it. A Purrsuader who tries to befriend a bee gets stung, and
that is -3 CHA for the swollen face, -1 AGI for the swelling, and +1 INT because
she will not do it again.

**The shape of a line.** Two beats: what arrives, then what this cat does with
it and what that costs or wins.

    You smile. The cat gets distracted by the weird motion.        -1 AGI
    You smile. The cat smiles back and takes it as encouragement.  +1 STR
    You smile. Your bond fills the cat with happy feelings.        +1 CHA +1 STR

Everything else follows from that:

* **The cat interprets, not the writer.** Read the object as this cat would,
  through its personality *and* its intelligence. A dim cat misreads what a
  clever one sees straight through, and an elephant shown to a Chonk is a
  remark about his size, so he loses strength over it.
* **The stat follows the state the cat ends in**, never the object itself.
  Emboldened is strength, wrong-footed is agility, bonded or adored is charm,
  worked-something-out is intellect, and insulted or demoralised goes down.
* **Both directions in every row.** An object that is good for all thirteen is
  not an object, it is a buff. The exception is a thing that frightens
  everybody, like the vacuum, where all thirteen drop but by different amounts,
  because a Ghost and a Chonk do not panic to the same degree.
* **Guessable first, twist second.** Most cells should be roughly what you would
  expect from that object and that cat. About a third can subvert it, mildly.
  Absurd is the seasoning, not the meal.

The rules, learned the hard way:

* **It happens in the arena.** A cat cannot "leave the room": there is no room,
  there is a fight, and everyone is watching. It can flinch, hide behind
  something, refuse to look, or get on top of the thing. It cannot exit.
* **It has to be about this object.** If the line would read the same with a
  different noun dropped in, it is filler and does not belong here.
* **It has to be about this cat.** A Loaf and a Zoom Gremlin do not have the
  same afternoon, ever.
* **The stats follow the story.** A cat that got what it wanted goes up in the
  attribute it used to get it. A cat that embarrassed itself goes down.
* Present tense, one thing happening, about a dozen words. No em dashes.

Progress is the number of objects in here against the 1,372 in the catalogue.
The panel shows the same count, so the work left is never in doubt.
"""

